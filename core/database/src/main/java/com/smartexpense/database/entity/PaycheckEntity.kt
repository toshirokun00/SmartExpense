package com.smartexpense.database.entity

import androidx.room.ColumnInfo
import androidx.room.Entity
import androidx.room.Index
import androidx.room.PrimaryKey
import java.util.UUID

/**
 * A single expected income payment. Bills are linked to a paycheck through
 * [PaycheckBillEntity] so the user can plan which bills each income covers.
 */
@Entity(
    tableName = "paychecks",
    indices = [
        Index(value = ["userId", "payDate"]),
        Index(value = ["clientId"], unique = true),
        // NULLs are distinct in SQLite, so one-time paychecks are unaffected.
        Index(value = ["scheduleClientId", "occurrenceDate"], unique = true)
    ]
)
data class PaycheckEntity(
    @PrimaryKey(autoGenerate = true)
    val id: Long = 0L,
    val userId: String,
    val clientId: String = UUID.randomUUID().toString(),
    val syncStatus: SyncStatus = SyncStatus.PENDING,
    val amount: Double,
    val payDate: Long,
    val label: String = "",
    val createdAt: Long,
    /** Recurring schedule that generated this cutoff, if any. */
    val scheduleClientId: String? = null,
    /** Start-of-day date this occurrence represents. */
    val occurrenceDate: Long? = null,
    /**
     * Tombstone for a deleted recurring cutoff. The row stays so the
     * deterministic occurrence id cannot be regenerated by the next sync.
     */
    @ColumnInfo(defaultValue = "0")
    val isSkipped: Boolean = false
)
