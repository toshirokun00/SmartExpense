package com.smartexpense.paycheck.state

import com.smartexpense.domain.model.Bill
import com.smartexpense.domain.model.BillPayment
import com.smartexpense.domain.model.PaycheckFrequency
import com.smartexpense.domain.model.coveredOccurrenceDueMillis
import java.time.ZoneId

/** Text-field values and bill selection captured by the paycheck form. */
data class PaycheckFormState(
    val amount: String = "",
    val payDateMillis: Long = System.currentTimeMillis(),
    val label: String = "",
    val selectedBillIds: Set<Long> = emptySet(),
    val editingPaycheckId: Long? = null,
    val isSaving: Boolean = false,
    /** New paycheck only: materialize this as a recurring payroll schedule. */
    val isRecurring: Boolean = false,
    val frequency: PaycheckFrequency = PaycheckFrequency.SEMI_MONTHLY,
    val firstDay: Int = 15,
    val secondDay: Int = 30,
    /** Editing an occurrence that was generated by a schedule. */
    val isRecurringOccurrence: Boolean = false,
    val scheduleClientId: String? = null,
    val scheduleStopped: Boolean = false
) {
    val isEditing: Boolean get() = editingPaycheckId != null

    /** The pay date is derived from the rule for new recurring paychecks. */
    val canEditPayDate: Boolean
        get() = !isRecurring && !isRecurringOccurrence
}

data class PaycheckFormUiState(
    val form: PaycheckFormState = PaycheckFormState(),
    val bills: List<Bill> = emptyList(),
    /** Payments recorded so far, used to pin bills to the cycle they cover. */
    val payments: List<BillPayment> = emptyList(),
    /**
     * Bills already assigned to a different paycheck. They are not suggested
     * here so the same bill is not covered twice.
     */
    val coveredBillIds: Set<Long> = emptySet(),
    /**
     * The cycle each bill selected on this paycheck belongs to. Paying a bill
     * advances its stored due date, so the form shows the pinned cycle instead
     * of the row's current date.
     */
    val dueByBillId: Map<Long, Long> = emptyMap(),
    /**
     * The cycle each listed bill shows even when it is unchecked: the plan's
     * pin when this cutoff covers it, otherwise the cycle this cutoff would
     * cover if the bill were checked. Keeping it here stops an unchecked bill
     * from jumping to another month group and hiding itself.
     */
    val cycleByBillId: Map<Long, Long> = emptyMap(),
    /** Zone used to resolve calendar dates consistently with the schedule. */
    val zoneId: ZoneId = ZoneId.systemDefault(),
    val isLoading: Boolean = true
) {
    /**
     * Bills the plan puts on this cutoff before any manual edits. They are
     * highlighted while unchecked, so a bill the user turned off is still easy
     * to spot and restore.
     */
    val suggestedBillIds: Set<Long>
        get() = dueByBillId.keys

    /**
     * The due date of the bill cycle this paycheck covers. A recurring bill's
     * row advances when a cycle is paid, so this stays on the cycle the
     * paycheck claimed instead of jumping to the next one.
     */
    fun coveredDueMillis(bill: Bill): Long = dueByBillId[bill.id]
        ?: coveredOccurrenceDueMillis(
            bill = bill,
            payDateMillis = form.payDateMillis,
            paidAtMillis = payments
                .filter { it.billId == bill.id }
                .map { it.paidAtMillis },
            zoneId = zoneId
        )

    fun billsCovered(): List<Bill> =
        bills.filter { it.id in form.selectedBillIds }

    /**
     * The due date the form shows for [bill]: the covered cycle once the bill is
     * selected here, the cycle this cutoff would cover otherwise, and the bill's
     * own due date when it was never planned for this cutoff. A bill the user
     * unchecks therefore stays under the same month header instead of jumping to
     * the raw due date of its row and appearing to vanish from the list.
     */
    fun displayedDueMillis(bill: Bill): Long =
        if (bill.id in form.selectedBillIds) {
            coveredDueMillis(bill)
        } else {
            cycleByBillId[bill.id] ?: bill.dueDateMillis
        }

    /**
     * Bills listed under "Bills to cover". Bills assigned to another paycheck are
     * hidden so the same bill is not planned twice; a bill on THIS paycheck stays
     * visible so its selection can still be seen and adjusted.
     *
     * Rows are ordered by the due date they display, so the list reads in
     * payment order and matches the paycheck card.
     */
    fun assignableBills(): List<Bill> = bills
        .filter { bill ->
            bill.id !in coveredBillIds || bill.id in form.selectedBillIds
        }
        .sortedWith(
            compareBy(
                { bill -> displayedDueMillis(bill) },
                { it.name },
                { it.id }
            )
        )

    fun assignedTotal(): Double = billsCovered().sumOf { it.amount }
}
