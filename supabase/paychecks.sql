-- Paycheck planning tables for SmartExpense.
--
-- Run this in the Supabase SQL editor. It is idempotent, so it is safe to run
-- again if you are unsure whether it was applied.
--
-- Column types match the existing public.bills table:
--   id         bigint
--   client_id  uuid
--   user_id    uuid
--   timestamps timestamptz
--   amount     numeric

-- Recurring payroll rules. Each rule materializes normal paycheck rows so a
-- single cutoff can be edited without changing the rest of the schedule.
create table if not exists public.paycheck_schedules (
    id          bigint generated by default as identity primary key,
    client_id   uuid        not null,
    user_id     uuid        not null references auth.users (id) on delete cascade,
    amount      numeric     not null check (amount >= 0),
    label       text        not null default '',
    frequency   text        not null,
    first_day   integer     not null,
    second_day  integer,
    start_date  timestamptz not null,
    end_date    timestamptz,
    is_active   boolean     not null default true,
    created_at  timestamptz not null default now(),
    constraint paycheck_schedules_client_id_key unique (client_id),
    constraint paycheck_schedules_frequency_check
        check (frequency in ('WEEKLY', 'BIWEEKLY', 'MONTHLY', 'SEMI_MONTHLY')),
    constraint paycheck_schedules_first_day_check
        check (first_day between 1 and 31),
    constraint paycheck_schedules_second_day_check
        check (second_day is null or second_day between 1 and 31)
);

create index if not exists paycheck_schedules_user_id_is_active_idx
    on public.paycheck_schedules (user_id, is_active);

create table if not exists public.paychecks (
    id                  bigint generated by default as identity primary key,
    client_id           uuid        not null,
    user_id             uuid        not null references auth.users (id) on delete cascade,
    amount              numeric     not null check (amount >= 0),
    pay_date            timestamptz not null,
    label               text        not null default '',
    schedule_client_id  uuid,
    occurrence_date     timestamptz,
    is_skipped          boolean     not null default false,
    created_at          timestamptz not null default now(),
    constraint paychecks_client_id_key unique (client_id),
    constraint paychecks_schedule_fkey
        foreign key (schedule_client_id)
        references public.paycheck_schedules (client_id) on delete set null
);

-- Existing installations created the table without the recurring columns.
alter table public.paychecks
    add column if not exists schedule_client_id uuid;
alter table public.paychecks
    add column if not exists occurrence_date timestamptz;
alter table public.paychecks
    add column if not exists is_skipped boolean not null default false;

do $$
begin
    if not exists (
        select 1 from pg_constraint
        where conname = 'paychecks_schedule_fkey'
          and conrelid = 'public.paychecks'::regclass
    ) then
        alter table public.paychecks
            add constraint paychecks_schedule_fkey
            foreign key (schedule_client_id)
            references public.paycheck_schedules (client_id) on delete set null;
    end if;
end $$;

-- NULL schedule ids stay distinct, so one-time paychecks are not constrained.
create unique index if not exists paychecks_schedule_occurrence_idx
    on public.paychecks (schedule_client_id, occurrence_date);

create index if not exists paychecks_user_id_pay_date_idx
    on public.paychecks (user_id, pay_date);

create table if not exists public.paycheck_bills (
    id                 bigint generated by default as identity primary key,
    client_id          uuid        not null,
    user_id            uuid        not null references auth.users (id) on delete cascade,
    paycheck_client_id uuid        not null,
    bill_client_id     uuid        not null,
    created_at         timestamptz not null default now(),
    constraint paycheck_bills_client_id_key unique (client_id),
    constraint paycheck_bills_paycheck_bill_key unique (paycheck_client_id, bill_client_id),
    constraint paycheck_bills_paycheck_fkey
        foreign key (paycheck_client_id)
        references public.paychecks (client_id) on delete cascade,
    constraint paycheck_bills_bill_fkey
        foreign key (bill_client_id)
        references public.bills (client_id) on delete cascade
);

create index if not exists paycheck_bills_user_id_idx
    on public.paycheck_bills (user_id);

create index if not exists paycheck_bills_paycheck_client_id_idx
    on public.paycheck_bills (paycheck_client_id);

create index if not exists paycheck_bills_bill_client_id_idx
    on public.paycheck_bills (bill_client_id);

alter table public.paycheck_schedules enable row level security;
alter table public.paychecks enable row level security;
alter table public.paycheck_bills enable row level security;

-- Paycheck schedules: a user can only see and change their own rows.
drop policy if exists "paycheck_schedules_select_own" on public.paycheck_schedules;
create policy "paycheck_schedules_select_own" on public.paycheck_schedules
    for select
    using (user_id = auth.uid());

drop policy if exists "paycheck_schedules_insert_own" on public.paycheck_schedules;
create policy "paycheck_schedules_insert_own" on public.paycheck_schedules
    for insert
    with check (user_id = auth.uid());

drop policy if exists "paycheck_schedules_update_own" on public.paycheck_schedules;
create policy "paycheck_schedules_update_own" on public.paycheck_schedules
    for update
    using (user_id = auth.uid())
    with check (user_id = auth.uid());

drop policy if exists "paycheck_schedules_delete_own" on public.paycheck_schedules;
create policy "paycheck_schedules_delete_own" on public.paycheck_schedules
    for delete
    using (user_id = auth.uid());

-- Paychecks: a user can only see and change their own rows. A recurring
-- paycheck must reference a schedule owned by the same user.
drop policy if exists "paychecks_select_own" on public.paychecks;
create policy "paychecks_select_own" on public.paychecks
    for select
    using (user_id = auth.uid());

drop policy if exists "paychecks_insert_own" on public.paychecks;
create policy "paychecks_insert_own" on public.paychecks
    for insert
    with check (
        user_id = auth.uid()
        and (
            schedule_client_id is null
            or exists (
                select 1
                from public.paycheck_schedules s
                where s.client_id = schedule_client_id
                  and s.user_id = auth.uid()
            )
        )
    );

drop policy if exists "paychecks_update_own" on public.paychecks;
create policy "paychecks_update_own" on public.paychecks
    for update
    using (user_id = auth.uid())
    with check (
        user_id = auth.uid()
        and (
            schedule_client_id is null
            or exists (
                select 1
                from public.paycheck_schedules s
                where s.client_id = schedule_client_id
                  and s.user_id = auth.uid()
            )
        )
    );

drop policy if exists "paychecks_delete_own" on public.paychecks;
create policy "paychecks_delete_own" on public.paychecks
    for delete
    using (user_id = auth.uid());

-- Paycheck bill assignments: own rows only, and both referenced rows must
-- belong to the same user.
drop policy if exists "paycheck_bills_select_own" on public.paycheck_bills;
create policy "paycheck_bills_select_own" on public.paycheck_bills
    for select
    using (user_id = auth.uid());

drop policy if exists "paycheck_bills_insert_own" on public.paycheck_bills;
create policy "paycheck_bills_insert_own" on public.paycheck_bills
    for insert
    with check (
        user_id = auth.uid()
        and exists (
            select 1
            from public.paychecks p
            where p.client_id = paycheck_client_id
              and p.user_id = auth.uid()
        )
        and exists (
            select 1
            from public.bills b
            where b.client_id = bill_client_id
              and b.user_id = auth.uid()
        )
    );

drop policy if exists "paycheck_bills_update_own" on public.paycheck_bills;
create policy "paycheck_bills_update_own" on public.paycheck_bills
    for update
    using (user_id = auth.uid())
    with check (
        user_id = auth.uid()
        and exists (
            select 1
            from public.paychecks p
            where p.client_id = paycheck_client_id
              and p.user_id = auth.uid()
        )
        and exists (
            select 1
            from public.bills b
            where b.client_id = bill_client_id
              and b.user_id = auth.uid()
        )
    );

drop policy if exists "paycheck_bills_delete_own" on public.paycheck_bills;
create policy "paycheck_bills_delete_own" on public.paycheck_bills
    for delete
    using (user_id = auth.uid());

grant select, insert, update, delete on public.paycheck_schedules to authenticated;
grant select, insert, update, delete on public.paychecks to authenticated;
grant select, insert, update, delete on public.paycheck_bills to authenticated;
grant usage, select on sequence public.paycheck_schedules_id_seq to authenticated;
grant usage, select on sequence public.paychecks_id_seq to authenticated;
grant usage, select on sequence public.paycheck_bills_id_seq to authenticated;
